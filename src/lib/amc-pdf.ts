/**
 * Print-to-PDF document generation for AMC contracts and invoices.
 * Opens a styled, print-ready document and triggers the browser's
 * native print dialog (Save as PDF).
 */
import type { AmcContract, AmcInvoice, AmcVisit } from "@/lib/secureops-data";
import { inr, logAudit } from "@/lib/secureops-data";

const BRAND_NAVY = "#0E4B87";
const BRAND_ORANGE = "#F39C12";

function shell(title: string, body: string) {
  return `<!doctype html><html><head><meta charset="utf-8"><title>${title}</title>
<style>
  *{box-sizing:border-box}
  body{font-family:"Inter Tight",Inter,-apple-system,Segoe UI,sans-serif;color:#16202b;margin:0;padding:40px;background:#fff}
  .doc{max-width:760px;margin:0 auto}
  header{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid ${BRAND_NAVY};padding-bottom:16px}
  .brand{font-size:22px;font-weight:800;color:${BRAND_NAVY};letter-spacing:-.02em}
  .brand span{color:${BRAND_ORANGE}}
  .muted{color:#63707f;font-size:12px;line-height:1.6}
  h1{font-size:17px;text-transform:uppercase;letter-spacing:.14em;margin:28px 0 4px}
  .chip{display:inline-block;background:${BRAND_ORANGE}1a;color:#8a5a04;border:1px solid ${BRAND_ORANGE}59;border-radius:999px;padding:3px 10px;font-size:11px;font-weight:600;text-transform:capitalize}
  table{width:100%;border-collapse:collapse;margin-top:14px;font-size:13px}
  th{text-align:left;background:#f2f5f8;color:${BRAND_NAVY};font-size:11px;text-transform:uppercase;letter-spacing:.08em;padding:9px 10px;border-bottom:1px solid #dfe6ed}
  td{padding:9px 10px;border-bottom:1px solid #eef2f6;vertical-align:top}
  td.r,th.r{text-align:right}
  .total td{font-weight:700;background:#f8fafc;border-bottom:none}
  footer{margin-top:36px;border-top:1px solid #dfe6ed;padding-top:12px;font-size:11px;color:#63707f}
  @media print{body{padding:0}@page{margin:16mm}}
</style></head>
<body><div class="doc">
  <header>
    <div>
      <div class="brand">DIGIVISTA <span>SECUREOPS</span></div>
      <div class="muted">Digivista Infotech Pvt Ltd<br/>Managed CCTV, Network &amp; IT Infrastructure Services<br/>support@digivista.in · +91 98200 00000</div>
    </div>
    <div class="muted" style="text-align:right">Generated<br/><strong>${new Date().toLocaleString("en-IN")}</strong></div>
  </header>
  ${body}
  <footer>This document is system-generated by Digivista SecureOps and is valid without signature. Subject to Mumbai jurisdiction.</footer>
</div>
<script>window.onload=function(){window.print()}</script>
</body></html>`;
}

function open(html: string) {
  const w = window.open("", "_blank", "width=900,height=1100");
  if (!w) return false;
  w.document.write(html);
  w.document.close();
  return true;
}

export function exportContractPdf(c: AmcContract, visits: AmcVisit[] = []) {
  const rows = visits
    .map(
      (v) =>
        `<tr><td>${v.id}</td><td>${v.scheduledOn}</td><td style="text-transform:capitalize">${v.type}</td><td>${v.engineer}</td><td style="text-transform:capitalize">${v.status}</td></tr>`,
    )
    .join("");
  const body = `
    <h1>Annual Maintenance Contract</h1>
    <p class="muted">Contract reference <strong>${c.id}</strong> · <span class="chip">${c.status}</span></p>
    <table>
      <tbody>
        <tr><th style="width:35%">Client</th><td>${c.company}</td></tr>
        <tr><th>Plan</th><td>${c.plan}</td></tr>
        <tr><th>Contract period</th><td>${c.startDate} to ${c.endDate}</td></tr>
        <tr><th>Contract value</th><td>${inr(c.value)} (${c.billingCycle.replace(/_/g, " ")} billing)</td></tr>
        <tr><th>Covered assets</th><td>${c.coveredAssets}</td></tr>
        <tr><th>Preventive visits / year</th><td>${c.visitsPerYear}</td></tr>
        <tr><th>Response SLA</th><td>${c.slaHours} hours</td></tr>
        <tr><th>Account owner</th><td>${c.owner}</td></tr>
        <tr><th>Auto renewal</th><td>${c.autoRenew ? "Enabled" : "Disabled"}</td></tr>
      </tbody>
    </table>
    <h1>Scope of Coverage</h1>
    <p class="muted">Preventive maintenance, corrective repairs, firmware and patch management, remote monitoring of covered
    endpoints, and priority helpdesk support within the agreed SLA. ${
      c.plan === "Comprehensive" ? "Spare parts are included." : c.plan === "Labour Only" ? "Spares and consumables are billed separately." : "Major spares are billed separately at approved rates."
    }</p>
    ${rows ? `<h1>Visit Schedule</h1><table><thead><tr><th>Visit</th><th>Date</th><th>Type</th><th>Engineer</th><th>Status</th></tr></thead><tbody>${rows}</tbody></table>` : ""}
  `;
  const ok = open(shell(`${c.id} — AMC Contract`, body));
  if (ok) logAudit("D. Administrator", `Exported contract PDF ${c.id}`, "AMC");
  return ok;
}

export function exportInvoicePdf(inv: AmcInvoice, contract?: AmcContract) {
  const tax = Math.round((inv.amount * inv.taxPercent) / 100);
  const body = `
    <h1>Tax Invoice</h1>
    <p class="muted">Invoice <strong>${inv.id}</strong> · <span class="chip">${inv.status}</span></p>
    <table>
      <tbody>
        <tr><th style="width:35%">Billed to</th><td>${inv.company}</td></tr>
        <tr><th>Contract</th><td>${inv.contractId}${contract ? ` · ${contract.plan}` : ""}</td></tr>
        <tr><th>Issued on</th><td>${inv.issuedOn}</td></tr>
        <tr><th>Due on</th><td>${inv.dueOn}</td></tr>
      </tbody>
    </table>
    <table>
      <thead><tr><th>Description</th><th class="r">Amount</th></tr></thead>
      <tbody>
        <tr><td>AMC services — ${contract?.billingCycle.replace(/_/g, " ") ?? "period"} charge for ${inv.contractId}</td><td class="r">${inr(inv.amount)}</td></tr>
        <tr><td>GST @ ${inv.taxPercent}%</td><td class="r">${inr(tax)}</td></tr>
        <tr class="total"><td>Total payable</td><td class="r">${inr(inv.amount + tax)}</td></tr>
      </tbody>
    </table>
    <p class="muted" style="margin-top:18px">Payment via NEFT/RTGS to Digivista Infotech Pvt Ltd. Please quote invoice number ${inv.id} in the payment reference.</p>
  `;
  const ok = open(shell(`${inv.id} — Tax Invoice`, body));
  if (ok) logAudit("Billing", `Exported invoice PDF ${inv.id}`, "AMC Invoices");
  return ok;
}

export function exportAmcRegisterPdf(contracts: AmcContract[]) {
  const rows = contracts
    .map(
      (c) =>
        `<tr><td>${c.id}</td><td>${c.company}</td><td>${c.plan}</td><td>${c.endDate}</td><td class="r">${inr(c.value)}</td><td style="text-transform:capitalize">${c.status}</td></tr>`,
    )
    .join("");
  const total = contracts.reduce((s, c) => s + c.value, 0);
  const body = `
    <h1>AMC Contract Register</h1>
    <p class="muted">${contracts.length} contract(s) · Total contracted value ${inr(total)}</p>
    <table>
      <thead><tr><th>Contract</th><th>Client</th><th>Plan</th><th>Expires</th><th class="r">Value</th><th>Status</th></tr></thead>
      <tbody>${rows}<tr class="total"><td colspan="4">Total</td><td class="r">${inr(total)}</td><td></td></tr></tbody>
    </table>
  `;
  const ok = open(shell("AMC Contract Register", body));
  if (ok) logAudit("D. Administrator", `Exported AMC register PDF (${contracts.length} contracts)`, "AMC");
  return ok;
}
